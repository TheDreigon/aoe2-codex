"""Extract the stats of the Scenario Editor units from an AoE2 DE installation.

Usage (from the repository root, with genieutils-py installed, e.g. in scripts/venv):
    scripts/venv/Scripts/python codex/tools/extract_scenario_units.py "<AoE2DE folder>"

Reads only the game's data file (resources/_common/dat/empires2_x2_p1.dat) and its English
key-value strings; nothing in the installation is modified. Matches the units listed in
codex/tools/scenario-units.md by their in-game name and writes:
  - codex/tools/scenario-units-stats.json   every matching unit ID with its base stats
  - codex/tools/scenario-units-stats.md     a readable table of the same stats
Stats are base values (Gaia's copy of the unit), before any civ bonus or technology.
"""
import json
import re
import sys
from pathlib import Path

from genieutils.datfile import DatFile

TOOLS = Path(__file__).resolve().parent
RESOURCES = ('Food', 'Wood', 'Stone', 'Gold')
MELEE_ARMOUR_CLASS = 4
PIERCE_ARMOUR_CLASS = 3


def load_strings(game_dir):
    strings = {}
    folder = Path(game_dir) / 'resources' / 'en' / 'strings' / 'key-value'
    for path in sorted(folder.glob('*.txt')):
        for line in path.read_text(encoding='utf-8-sig').splitlines():
            m = re.match(r'^(\d+)\s+"(.*)"\s*$', line)
            if m:
                strings.setdefault(int(m.group(1)), m.group(2))
    return strings


def wanted_names():
    names = []
    for line in (TOOLS / 'scenario-units.md').read_text(encoding='utf-8').splitlines():
        m = re.match(r'^\| ([^|]+?) \|', line)
        if m and m.group(1) not in ('Unit', '---'):
            names.append(re.sub(r'\s*\(Age of Empires II\)$', '', m.group(1)).strip())
    return names


def rnd(value):
    return round(value, 2) if value is not None else None


def stat_row(unit):
    t50 = unit.type_50
    armours = {a.class_: a.amount for a in t50.armours} if t50 else {}
    cost = {}
    if unit.creatable:
        for rc in unit.creatable.resource_costs:
            if 0 <= rc.type < 4 and rc.amount:
                cost[RESOURCES[rc.type]] = rc.amount
    return {
        'id': unit.id,
        'internal_name': unit.name,
        'class': unit.class_,
        'hp': unit.hit_points,
        'attack': t50.displayed_attack if t50 else None,
        'range': rnd(t50.displayed_range) if t50 else None,
        'melee_armour': armours.get(MELEE_ARMOUR_CLASS),
        'pierce_armour': armours.get(PIERCE_ARMOUR_CLASS),
        'reload_time': rnd(t50.reload_time) if t50 else None,
        'speed': rnd(unit.speed),
        'line_of_sight': rnd(unit.line_of_sight),
        'cost': cost,
        'train_time': unit.creatable.train_locations[0].train_time if unit.creatable and unit.creatable.train_locations else None,
        'attacks': [{'class': a.class_, 'amount': a.amount} for a in t50.attacks] if t50 else [],
    }


def main(game_dir):
    sys.stdout.reconfigure(encoding='utf-8')
    strings = load_strings(game_dir)
    dat = DatFile.parse(Path(game_dir) / 'resources' / '_common' / 'dat' / 'empires2_x2_p1.dat')
    by_name = {}
    for unit in dat.civs[0].units:
        if unit and unit.hit_points > 0:
            name = strings.get(unit.language_dll_name)
            if name:
                by_name.setdefault(name.lower(), []).append(unit)
    result = {}
    for name in wanted_names():
        units = by_name.get(name.lower(), [])
        result[name] = [stat_row(u) for u in units]
        print(f'{name}: {len(units)} match(es)')
    (TOOLS / 'scenario-units-stats.json').write_text(json.dumps(result, indent=1, ensure_ascii=False) + '\n', encoding='utf-8')
    lines = ['# Scenario Editor units: base stats',
             '',
             'Generated by `extract_scenario_units.py` from the game data of an AoE2 DE installation. '
             'Base values (Gaia), before civ bonuses and technologies. A name can match several unit IDs '
             '(campaign variants); the first is usually the one the Scenario Editor places.',
             '',
             '| Unit | ID | HP | Attack | Range | Armour (melee/pierce) | Speed | Cost | Train time |',
             '|---|---|---|---|---|---|---|---|---|']
    for name, rows in result.items():
        if not rows:
            lines.append(f'| {name} | not found | | | | | | | |')
        for r in rows:
            cost = ', '.join(f'{v} {k}' for k, v in r['cost'].items()) or '—'
            lines.append(f"| {name} | {r['id']} | {r['hp']} | {r['attack']} | {r['range']} | "
                         f"{r['melee_armour']}/{r['pierce_armour']} | {r['speed']} | {cost} | {r['train_time']} |")
    (TOOLS / 'scenario-units-stats.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main(sys.argv[1])
